import { readFileSync, writeFileSync } from "node:fs";

const source = new URL(
  "../../../generate_language/src/languages.json",
  import.meta.url,
);
const target = new URL(
  "../src/generated/formulaLanguageIds.ts",
  import.meta.url,
);
const ids = Object.keys(JSON.parse(readFileSync(source, "utf8"))).sort();
const expected = `// Generated by scripts/generate-language-ids.js; do not edit.\nexport const formulaLanguageIds: readonly string[] = [\n${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}\n];\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== expected) {
    throw new Error(
      "Formula language IDs are stale; run npm run generate:language-ids",
    );
  }
} else {
  writeFileSync(target, expected);
}
